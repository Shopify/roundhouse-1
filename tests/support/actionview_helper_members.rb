# Prints src/view_helpers/actionview_members.txt from the pinned Rails
# (tests/support/rails_oracle.rb): for each `ActionView::Helpers` module
# (and `ActiveSupport::NumberHelper`), every method an includer can call
# on implicit self — public and private, from the module and from all
# the modules including it brings along. Measured by including it into
# a fresh class, so ActiveSupport::Concern dependencies (`ActionView::
# Helpers` itself) are resolved the way Ruby resolves them.
#
#   ruby tests/support/actionview_helper_members.rb > src/view_helpers/actionview_members.txt
#
# tests/view_helper_includes.rs regenerates it and compares.
require_relative "rails_oracle"
RailsOracle.activate("activesupport", "actionview", "actionpack", "activemodel")
require "action_view"
require "active_support/number_helper"

modules = [ActionView::Helpers, ActiveSupport::NumberHelper]
ActionView::Helpers.constants(false).sort.each do |name|
  value = ActionView::Helpers.const_get(name)
  modules << value if value.instance_of?(Module)
end
puts "# Generated by tests/support/actionview_helper_members.rb from #{RailsOracle.label}."
puts "# <module>: the methods an includer reaches on implicit self through it."
modules.uniq.sort_by(&:name).each do |mod|
  includer = Class.new { include mod }
  owners = includer.ancestors.take_while { |a| a != Object } - [includer]
  names = owners.flat_map { |a| a.instance_methods(false) + a.private_instance_methods(false) }.uniq.map(&:to_s).sort
  puts "#{mod.name}: #{names.join(" ")}"
end
